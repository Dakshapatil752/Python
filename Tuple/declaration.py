"""
Examples: Declaration of tuple in Python
"""

# Creating a tuple using parentheses
my_tuple = (1, 2, 3, 4)
print("Tuple using parentheses:", my_tuple)

# Creating a tuple without parentheses
another_tuple = 5, 6, 7
print("Tuple without parentheses:", another_tuple)

# Creating an empty tuple
empty_tuple = ()
print("Empty tuple:", empty_tuple)

# Creating a tuple with mixed data types
mixed_tuple = (10, "Python", 3.14)
print("Tuple with mixed data types:", mixed_tuple)

# Creating a single-element tuple (note the comma)
single_tuple = (42,)
print("Single-element tuple:", single_tuple)
