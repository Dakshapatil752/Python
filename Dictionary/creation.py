"""
Examples: Creation of dictionary in Python
"""

# Creating a dictionary using curly braces
my_dict = {'name': 'Alice', 'age': 25, 'city': 'New York'}
print("Dictionary using curly braces:", my_dict)

# Creating a dictionary using the dict() constructor
another_dict = dict(id=101, subject='Math', score=95)
print("Dictionary using dict() constructor:", another_dict)

# Creating an empty dictionary
empty_dict = {}
print("Empty dictionary:", empty_dict)

# Creating a dictionary from a list of tuples
tuple_dict = dict([('a', 1), ('b', 2), ('c', 3)])
print("Dictionary from list of tuples:", tuple_dict)
