# Using single quotes
str1 = 'Hello, World!'
print("Single quotes:", str1)

# Using double quotes
str2 = "Python Programming"
print("Double quotes:", str2)

# Using triple quotes for multi-line strings
str3 = '''This is
a multi-line
string.'''
print("Triple quotes (multi-line):", str3)

# Declaring an empty string
empty_str = ""
print("Empty string:", empty_str)

# String with escape characters
str4 = "Line1\nLine2\tTabbed"
print("Escape characters:", str4)
